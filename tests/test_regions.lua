local R=require("wr_regions")
local b=assert(R.NormalizeBounds({x1=50,z1=20,x2=-50,z2=-20}))
assert(b.x1==-50 and b.x2==50 and b.z1==-20 and b.z2==20)
assert(R.Inside(b,50,20) and not R.Inside(b,0,21))
assert(R.NormalizeBounds({x1=0,z1=0,x2=160,z2=160}))
assert(not R.NormalizeBounds({x1=0,z1=0,x2=161,z2=20}))
assert(not R.NormalizeBounds({x1=0,z1=0,x2=2,z2=20}))
assert(not R.NormalizeBounds({x1=0/0,z1=0,x2=20,z2=20}))
assert(not R.NormalizeBounds({x1=math.huge,z1=0,x2=20,z2=20}))
local c=R.Copy({id=1,label="区",mode="farm",bounds=b})
c.bounds.x1=0
assert(b.x1==-50)
print("WR_REGIONS_PASS bounds validation and rectangular filtering")
