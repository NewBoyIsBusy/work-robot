-- Real renderer integration checks; only loaded by run_commander_ui.py.
assert(TheWorld and not TheWorld.ismastersim and ThePlayer and ThePlayer.HUD)
local json=require("json")
local count=0
local function pass(name)count=count+1 print("WR_UI_PASS "..name)end
local function later(fn,delay)
 TheWorld:DoStaticTaskInTime(delay or .6,function()local ok,err=pcall(fn)if not ok then print("WR_UI_FAILURE "..tostring(err))end end)
end
local function find(prefab)
 for _,e in pairs(Ents)do if e.prefab==prefab and e:IsValid()then return e end end
end
local robot=find("work_robot")local chest=find("treasurechest")local bush=find("berrybush")local log=find("log")
assert(robot and chest and bush and log,"fixture entities were not replicated")
local ui=assert(WORK_ROBOT_FOCUS_CONTROLLER,"focus HUD was not constructed")
assert(ACTIONS.WR_FOCUS and ACTIONS.WR_TARGET and ACTIONS.WR_REPAIR)
local _,focusaction=ThePlayer.components.playeractionpicker:DoGetMouseActions(robot:GetPosition(),robot)
assert(focusaction and focusaction.action==ACTIONS.WR_FOCUS,"client right-click picker did not expose focus")
pass("focus actions and native HUD construct in a real client")
local function action(target,definition)
 local pc=ThePlayer.components.playercontroller local p=target:GetPosition()
 local platform,x,z=pc:GetPlatformRelativePosition(p.x,p.z)
 SendRPCToServer(RPC.RightClick)
 SendRPCToServer(RPC.RightClick,definition.code,x,z,target,nil,true,pc:EncodeControlMods(),nil,definition.mod_name,platform,platform~=nil)
end
action(robot,ACTIONS.WR_FOCUS)
later(function()
 assert(WORK_ROBOT_FOCUS_GUID==robot.GUID and ui.guid==robot.GUID,
  tostring(WORK_ROBOT_FOCUS_GUID).." / "..tostring(ui.guid).." / "..tostring(robot.GUID))
 assert(ui:IsVisible()and ui.help:IsVisible()and TheCamera.target==nil)
 assert(ui.cam and math.abs(ui.cam.x-robot:GetPosition().x)<.2)
 pass("right-click focus enters an unlocked camera centered on the robot")
 local before=ui.cam.x local old=TheInput.GetAnalogControlValue
 TheInput.GetAnalogControlValue=function(_,control)return control==CONTROL_MOVE_RIGHT and 1 or 0 end
 ui:TickCamera(.5)TheInput.GetAnalogControlValue=old
 assert(math.abs(ui.cam.x-before)>1 or math.abs(ui.cam.z-robot:GetPosition().z)>1)
 assert(TheCamera.target==nil,"camera became locked to the robot")
 pass("WASD camera input pans without moving the focus target")
 local _,targetaction=ThePlayer.components.playeractionpicker:DoGetMouseActions(chest:GetPosition(),chest)
 assert(targetaction and targetaction.action==ACTIONS.WR_TARGET,"client right-click picker did not expose target selection")
 action(chest,ACTIONS.WR_TARGET)
 later(function()
  local state=json.decode(robot._wr_state:value())assert(state.b==1 and state.t==0)
  pass("remote right-click assigns a target container")
  action(bush,ACTIONS.WR_TARGET)
  later(function()
   action(log,ACTIONS.WR_TARGET)
   later(function()
    local state=json.decode(robot._wr_state:value())assert(state.b==1 and state.t==2)
    assert(state.p and #state.p>=1,"robot did not publish an action path")
    ui:OnUpdate(.2)assert(ui.lines[1]:IsVisible(),"path line is hidden")
    pass("multiple work targets persist and the current path is drawn as a line")
    action(bush,ACTIONS.WR_TARGET)
    later(function()
     local state=json.decode(robot._wr_state:value())assert(state.t==1)
     pass("right-clicking an assigned object removes only that target")
     action(robot,ACTIONS.WR_FOCUS)
     later(function()
      assert(WORK_ROBOT_FOCUS_GUID==0 and ui.guid==0 and TheCamera.target==ThePlayer)
      pass("right-clicking the focused robot exits and restores the player camera")
      print("WR_UI_SUCCESS "..count.." checks")
     end)
    end)
   end,.35)
  end,.25)
 end,.35)
end,.8)
